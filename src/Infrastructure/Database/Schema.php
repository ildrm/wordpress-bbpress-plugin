<?php
declare(strict_types=1);
namespace ForumIntelligence\Infrastructure\Database;
final class Schema {
	public const VERSION = 8;
	public const TABLES  = array( 'solutions', 'signals', 'events', 'links', 'notifications', 'cases', 'jobs', 'chunks', 'records', 'metrics', 'limits' );
	public function install(): void {
		global $wpdb;
		require_once ABSPATH . 'wp-admin/includes/upgrade.php';
		$previous    = (int) get_option( 'fi_schema_version', 0 );
		$charset     = $wpdb->get_charset_collate();
		$definitions = array(
			'solutions'     => 'topic_id bigint(20) unsigned NOT NULL,
                version bigint(20) unsigned NOT NULL DEFAULT 0,
                solved tinyint(1) NOT NULL DEFAULT 0,
                primary_reply bigint(20) unsigned NOT NULL DEFAULT 0,
                answers longtext NOT NULL,
                actor_id bigint(20) unsigned NOT NULL DEFAULT 0,
                updated_at datetime NOT NULL,
                PRIMARY KEY  (topic_id)',
			'signals'       => 'id bigint(20) unsigned NOT NULL AUTO_INCREMENT,
                object_id bigint(20) unsigned NOT NULL,
                user_id bigint(20) unsigned NOT NULL,
                kind varchar(40) NOT NULL,
                value int NOT NULL DEFAULT 1,
                created_at datetime NOT NULL,
                updated_at datetime NOT NULL,
                PRIMARY KEY  (id),
                UNIQUE KEY identity (object_id,user_id,kind),
                KEY object_kind (object_id,kind,value),
                KEY user_kind (user_id,kind,updated_at),
                KEY recent (updated_at,object_id)',
			'events'        => 'id bigint(20) unsigned NOT NULL AUTO_INCREMENT,
                kind varchar(60) NOT NULL,
                object_id bigint(20) unsigned NOT NULL DEFAULT 0,
                actor_id bigint(20) unsigned NOT NULL DEFAULT 0,
                subject_id bigint(20) unsigned NOT NULL DEFAULT 0,
                points int NOT NULL DEFAULT 0,
                event_key varchar(191) DEFAULT NULL,
                payload longtext NOT NULL,
                created_at datetime NOT NULL,
                PRIMARY KEY  (id),
                UNIQUE KEY event_key (event_key),
                KEY subject_kind (subject_id,kind,id),
                KEY subject_object (subject_id,object_id),
                KEY object_kind (object_id,kind,id),
                KEY retention (created_at)',
			'links'         => "id bigint(20) unsigned NOT NULL AUTO_INCREMENT,
                user_id bigint(20) unsigned NOT NULL DEFAULT 0,
                source_id bigint(20) unsigned NOT NULL DEFAULT 0,
                target_id bigint(20) unsigned NOT NULL DEFAULT 0,
                kind varchar(40) NOT NULL,
                label varchar(191) NOT NULL DEFAULT '',
                payload longtext NOT NULL,
                created_at datetime NOT NULL,
                PRIMARY KEY  (id),
                UNIQUE KEY identity (user_id,source_id,target_id,kind,label),
                KEY source_kind (source_id,kind,id),
                KEY user_kind (user_id,kind,id),
                KEY target_kind (target_id,kind,id)",
			'notifications' => 'id bigint(20) unsigned NOT NULL AUTO_INCREMENT,
                user_id bigint(20) unsigned NOT NULL,
                object_id bigint(20) unsigned NOT NULL,
                kind varchar(40) NOT NULL,
                event_key varchar(191) NOT NULL,
                is_read tinyint(1) NOT NULL DEFAULT 0,
                emailed tinyint(1) NOT NULL DEFAULT 0,
                created_at datetime NOT NULL,
                PRIMARY KEY  (id),
                UNIQUE KEY delivery (user_id,event_key),
                KEY inbox (user_id,is_read,id),
                KEY chronological (user_id,id),
                KEY category (user_id,kind,id),
                KEY mail (emailed,created_at,id)',
			'cases'         => "id bigint(20) unsigned NOT NULL AUTO_INCREMENT,
                object_id bigint(20) unsigned NOT NULL,
                reporter_id bigint(20) unsigned DEFAULT NULL,
                assignee_id bigint(20) unsigned NOT NULL DEFAULT 0,
                reason varchar(40) NOT NULL,
                status varchar(20) NOT NULL DEFAULT 'new',
                priority int NOT NULL DEFAULT 0,
                notes longtext NOT NULL,
                created_at datetime NOT NULL,
                updated_at datetime NOT NULL,
                PRIMARY KEY  (id),
                UNIQUE KEY report (object_id,reporter_id),
                KEY queue (status,priority,id),
                KEY reporter (reporter_id,id)",
			'jobs'          => "id bigint(20) unsigned NOT NULL AUTO_INCREMENT,
                kind varchar(40) NOT NULL,
                job_key varchar(191) NOT NULL,
                payload longtext NOT NULL,
                status varchar(20) NOT NULL DEFAULT 'queued',
                attempts int NOT NULL DEFAULT 0,
                revision bigint(20) unsigned NOT NULL DEFAULT 1,
                available_at datetime NOT NULL,
                lease_until datetime DEFAULT NULL,
                lease_token varchar(64) NOT NULL DEFAULT '',
                error_code varchar(80) NOT NULL DEFAULT '',
                updated_at datetime NOT NULL,
                PRIMARY KEY  (id),
                UNIQUE KEY job_key (job_key),
                KEY claim (status,available_at,id),
                KEY leases (status,lease_until)",
			'chunks'        => "source_id bigint(20) unsigned NOT NULL,
                forum_id bigint(20) unsigned NOT NULL,
                source_type varchar(20) NOT NULL,
                content_hash char(64) NOT NULL,
                visibility varchar(20) NOT NULL,
                content longtext NOT NULL,
                vector longtext NOT NULL,
                vector_binary longblob DEFAULT NULL,
                model varchar(100) NOT NULL DEFAULT '',
                updated_at datetime NOT NULL,
                PRIMARY KEY  (source_id),
                KEY forum_source (forum_id,source_type,source_id),
                KEY vector_candidates (visibility,source_id),
                FULLTEXT KEY content_search (content)",
			'records'       => 'id bigint(20) unsigned NOT NULL AUTO_INCREMENT,
                kind varchar(40) NOT NULL,
                owner_id bigint(20) unsigned NOT NULL DEFAULT 0,
                object_id bigint(20) unsigned NOT NULL DEFAULT 0,
                record_key varchar(191) NOT NULL,
                version bigint(20) unsigned NOT NULL DEFAULT 0,
                payload longtext NOT NULL,
                created_at datetime NOT NULL,
                updated_at datetime NOT NULL,
                PRIMARY KEY  (id),
                UNIQUE KEY record_key (record_key),
                KEY kind_id (kind,id),
                KEY owner_kind (owner_id,kind,id),
                KEY object_kind (object_id,kind,id)',
			'metrics'       => 'day date NOT NULL,
                kind varchar(60) NOT NULL,
                count bigint(20) unsigned NOT NULL DEFAULT 0,
                PRIMARY KEY  (day,kind)',
			'limits'        => 'bucket char(64) NOT NULL,
                window_start bigint(20) unsigned NOT NULL,
                count int unsigned NOT NULL DEFAULT 0,
                PRIMARY KEY  (bucket,window_start)',
		);
		foreach ( $definitions as $suffix => $definition ) {
			dbDelta( "CREATE TABLE {$wpdb->prefix}fi_$suffix ($definition) ENGINE=InnoDB $charset;" );
			if ( $wpdb->last_error !== '' ) {
				throw new \RuntimeException( 'Schema migration failed for ' . $suffix ); }
		}
		if ( $previous > 0 && $previous < 8 && ! get_option( 'fi_vector_cache_upgrade', '' ) ) {
			add_option( 'fi_vector_cache_upgrade', bin2hex( random_bytes( 8 ) ), '', false );
		}
		update_option( 'fi_schema_version', self::VERSION, false );
	}
}
